import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { FreshMFADialog } from '../fresh-mfa-dialog'
it('keeps keyboard focus inside the exact review and supports Escape cancellation', () => {
  const close = vi.fn()
  render(<FreshMFADialog title="Confirm action" onClose={close} onSubmit={vi.fn()} onSuccess={vi.fn()}><p>Exact digest</p></FreshMFADialog>)
  const input = screen.getByLabelText('Fresh MFA code')
  fireEvent.change(input, { target: { value: '123456' } })
  const confirm = screen.getByText('Confirm with fresh MFA')
  confirm.focus()
  fireEvent.keyDown(confirm, { key: 'Tab' })
  expect(input).toHaveFocus()
  fireEvent.keyDown(input, { key: 'Tab', shiftKey: true })
  expect(confirm).toHaveFocus()
  fireEvent.keyDown(confirm, { key: 'Escape' })
  expect(close).toHaveBeenCalledTimes(1)
})
it('restores focus to the invoking control and clears masked code when cancelled', () => {
  const control = document.createElement('button'); document.body.append(control); control.focus()
  const view = render(<FreshMFADialog title="Confirm action" onClose={vi.fn()} onSubmit={vi.fn()} onSuccess={vi.fn()}><p>Exact digest</p></FreshMFADialog>)
  expect(screen.getByLabelText('Fresh MFA code')).toHaveAttribute('type', 'password')
  fireEvent.change(screen.getByLabelText('Fresh MFA code'), { target: { value: '123456' } })
  view.unmount()
  expect(control).toHaveFocus()
  control.remove()
})
it('does not expose a reflected MFA value or offer a retry after a network refusal', async () => {
  const submit = vi.fn().mockRejectedValue(new Error('PRIVATE-123456'))
  const success = vi.fn()
  render(<FreshMFADialog title="Confirm action" onClose={vi.fn()} onSubmit={submit} onSuccess={success}><p>Exact digest</p></FreshMFADialog>)
  fireEvent.change(screen.getByLabelText('Fresh MFA code'), { target: { value: 'abc123456' } })
  expect(screen.getByLabelText('Fresh MFA code')).toHaveValue('123456')
  fireEvent.click(screen.getByText('Confirm with fresh MFA'))
  await waitFor(() => expect(screen.getByRole('alert')).toHaveTextContent('proof will not be reused'))
  expect(screen.queryByLabelText('Fresh MFA code')).not.toBeInTheDocument()
  expect(screen.queryByText('PRIVATE-123456')).not.toBeInTheDocument()
  expect(submit).toHaveBeenCalledTimes(1)
  expect(success).not.toHaveBeenCalled()
})
